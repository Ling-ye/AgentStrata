"""Evaluation worker operations supplied by the service runtime."""
from __future__ import annotations

from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from types import MappingProxyType
from typing import Literal, Protocol

WorkerPidStatus = Literal["matched", "unknown", "exited"]
WorkerExitCallback = Callable[[int | None], None]


@dataclass(frozen=True)
class WorkerLaunchRequest:
    command: tuple[str, ...]
    cwd: Path
    environment: Mapping[str, str] = field(repr=False)

    def __post_init__(self) -> None:
        object.__setattr__(self, "environment", MappingProxyType(dict(self.environment)))


class WorkerProcess(Protocol):
    @property
    def pid(self) -> int: ...
    def poll(self) -> int | None: ...
    def wait(self, timeout: float | None = None) -> int: ...
    def terminate(self) -> None: ...


class PreparedWorker(Protocol):
    @property
    def process(self) -> WorkerProcess: ...
    def release(self) -> None: ...
    def close(self) -> None: ...


class EvaluationWorkerPort(Protocol):
    def prepare(self, request: WorkerLaunchRequest) -> PreparedWorker: ...
    def observe(self, pid: int, directory: Path) -> WorkerPidStatus: ...
    def discover(self, directory: Path) -> Sequence[int]: ...
    def exists(self, pid: int) -> bool: ...
    def request_stop(self, pid: int) -> None: ...
    def force_stop(self, pid: int) -> None: ...
    def abort(self, process: WorkerProcess) -> None: ...
    def watch(self, process: WorkerProcess, on_exit: WorkerExitCallback) -> None: ...
    def watch_inherited(self, pid: int, directory: Path, on_exit: WorkerExitCallback) -> None: ...
